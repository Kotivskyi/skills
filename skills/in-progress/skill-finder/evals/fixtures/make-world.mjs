#!/usr/bin/env node
// Builds the eval world for skill-finder. Usage: node make-world.mjs [dest]
// The default dest is /tmp/skill-finder-world. See evals/README.md.
// SKILL.md files are written here at run time and never committed, because
// the repo sync script treats every committed SKILL.md as a skill.
import { existsSync, mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { buildCatalog } from '../../scripts/index-catalog.mjs';
import { writeSkill } from '../../scripts/fixtures/catalog/build.mjs';
import { isMain } from '../../scripts/lib/args.mjs';

const MARKER = '.skill-finder-world';
const ENVS = ['staging', 'preview', 'canary', 'sandbox', 'demo', 'qa', 'perf', 'edge', 'blue', 'green', 'nightly', 'pilot'];
const FEATURES = ['heartbeat batching', 'herd rotation', 'fence alerts', 'tag pairing', 'gps smoothing', 'battery reports', 'pasture maps', 'firmware rollout', 'geofence sync', 'collar reboot', 'water points', 'weather feed'];
const CHECKS = ['grafana panels', 'error budget', 'queue depth', 'latency graph', 'crash reports', 'log volume', 'pod restarts', 'memory curve', 'alert noise', 'cpu headroom', 'trace sampling', 'uptime probe'];
const A_WORDS = ['alpha', 'bravo', 'charlie', 'delta', 'echo', 'foxtrot', 'golf', 'hotel', 'india', 'juliet'];
const B_WORDS = ['herds', 'pastures', 'collars', 'tags', 'gateways', 'farms', 'plans', 'zones', 'devices', 'fences'];
const C_WORDS = ['export', 'import', 'backfill', 'rollup', 'cleanup', 'audit', 'sync', 'merge', 'replay', 'archive'];
const NEAR_MISS = [
  (j) => `Why does the CI runner on ${A_WORDS[j]} time out during ${B_WORDS[j]} ${C_WORDS[j]} checks?`,
  (j) => `Draft a staging runbook covering ${A_WORDS[j]} alerts and ${B_WORDS[j]} ${C_WORDS[j]} failures.`,
  (j) => `How does the ${A_WORDS[j]} simulator seed ${B_WORDS[j]} ${C_WORDS[j]} fixtures for tests?`
];

function write(file, text) {
  mkdirSync(path.dirname(file), { recursive: true });
  writeFileSync(file, text);
}

const json = (value) => `${JSON.stringify(value, null, 2)}\n`;
const at = (day, minute) => new Date(Date.parse(`${day}T09:00:00.000Z`) + minute * 60000).toISOString();

export function buildWorld(dest) {
  if (existsSync(dest) && readdirSync(dest).length && !existsSync(path.join(dest, MARKER))) {
    throw new Error(`${dest} is not empty and is not a skill-finder world. Choose another folder.`);
  }
  rmSync(dest, { recursive: true, force: true });
  const project = path.join(dest, 'project');
  const home = path.join(dest, 'home');
  const store = path.join(dest, 'claude-store');
  const archive = path.join(project, 'openspec', 'changes', 'archive');
  write(path.join(dest, MARKER), 'Generated by evals/fixtures/make-world.mjs.\n');
  write(path.join(project, '.gitignore'), '.skill-finder/\n');

  let seq = 0;
  const groups = {};
  const session = (group, { day, title, prompts, skills = [], commands = [], bash = [], corrections = [] }) => {
    seq += 1;
    const id = `00000000-0000-4000-8000-${String(seq).padStart(12, '0')}`;
    const rows = [];
    let minute = 0;
    const base = () => ({ parentUuid: null, isSidechain: false, uuid: `r${rows.length + 1}`, timestamp: at(day, minute++), cwd: project, sessionId: id });
    const user = (content) => rows.push({ ...base(), type: 'user', message: { role: 'user', content }, origin: { kind: 'human' } });
    const assistant = (content) => rows.push({ ...base(), type: 'assistant', message: { id: `m${rows.length + 1}`, role: 'assistant', content } });
    const tool = (name, input) => assistant([{ type: 'tool_use', id: `t${rows.length + 1}`, name, input }]);
    for (const command of commands) user(`<command-name>/${command}</command-name>\n<command-message>${command}</command-message>\n<command-args></command-args>`);
    prompts.forEach((prompt, index) => {
      user(prompt);
      if (index === 0) {
        for (const skill of skills) tool('Skill', { skill });
        for (const command of bash) tool('Bash', { command });
      }
      assistant([{ type: 'text', text: `Step ${index + 1} is done.` }]);
    });
    for (const text of corrections) {
      user(text);
      assistant([{ type: 'text', text: 'Fixed.' }]);
    }
    rows.push({ type: 'ai-title', aiTitle: title, sessionId: id });
    const file = path.join(store, `${id}.jsonl`);
    write(file, `${rows.map((row) => JSON.stringify(row)).join('\n')}\n`);
    (groups[group] ??= []).push({ id, file, prompt: prompts[0] });
  };

  // One-off work before the previous run. It must stay below the rule.
  session('oneOff', { day: '2026-08-28', title: 'Rotate the grafana token', prompts: ['Rotate the grafana admin token and update the secret in the staging vault today.'] });

  // new-skill: 12 deploy sessions on 12 days. No catalog skill covers them.
  for (let i = 0; i < 12; i += 1) {
    session('deploy', {
      day: `2026-09-${String(i + 2).padStart(2, '0')}`,
      title: 'Deploy sim runner to staging',
      prompts: [
        `Deploy the sim runner to ${ENVS[i]} with ${FEATURES[i]} enabled and verify the ${CHECKS[i]} afterwards.`,
        `Push the simulator build to ${ENVS[i]} again, then watch the ${CHECKS[(i + 7) % 12]} for ${FEATURES[(i + 5) % 12]} regressions.`,
        `Please roll the sim runner forward on ${ENVS[i]} and post links to the ${CHECKS[i]} for ${FEATURES[i]}.`
      ],
      bash: ['./scripts/deploy-sim.sh staging', 'pnpm test --filter sim']
    });
  }

  // silent-skill: write-http-files matches this work and never fires.
  ['devices', 'herds', 'plans'].forEach((api, k) => session('http', {
    day: ['2026-09-03', '2026-09-06', '2026-09-10'][k],
    title: `Write HTTP request files for the ${api} API`,
    prompts: [
      `Write .http request files for the ${api} API so I can run them from the editor.`,
      `Add an auth token variable to the ${api} requests and an environment file for staging.`
    ]
  }));

  // misfiring-skill: release-notes fires and the user corrects the package manager.
  [1, 2, 3].forEach((k) => session('releaseNotes', {
    day: ['2026-09-05', '2026-09-08', '2026-09-12'][k - 1],
    title: `Release notes for v1.${k}`,
    commands: ['release-notes'],
    skills: ['release-notes'],
    prompts: [`Write the release notes for v1.${k} from the merged pull requests.`],
    corrections: ['no, use pnpm not npm when you build the release notes']
  }));

  // misfiring-skill on a plugin: the edit must be staged, never applied.
  [1, 2, 3].forEach((k) => session('changelog', {
    day: ['2026-09-06', '2026-09-09', '2026-09-11'][k - 1],
    title: `Update the changelog for sprint ${k}`,
    skills: ['acme-tools:changelog-writer'],
    prompts: [`Update the changelog for sprint ${k} with the merged work.`],
    corrections: ['no, the changelog must follow the keep a changelog format with unreleased on top']
  }));

  // Near-miss noise: prompts that share a few words with the deploy work.
  for (let j = 0; j < 10; j += 1) {
    session('noise', { day: `2026-09-${String(j + 2).padStart(2, '0')}`, title: `Maintenance ${A_WORDS[j]}`, prompts: NEAR_MISS.map((template) => template(j)) });
  }

  // Catalog: two repo skills and one plugin skill.
  writeSkill(path.join(project, '.agents', 'skills', 'write-http-files'), {
    name: 'write-http-files',
    description: 'Author .http request files in the HTTP Request in Editor format. Use when the user wants to create or edit runnable HTTP requests, turn a curl command or an OpenAPI spec into a .http file, or add auth variables and environments to request files.'
  });
  writeSkill(path.join(project, '.agents', 'skills', 'release-notes'), {
    name: 'release-notes',
    description: 'Write release notes from merged pull requests. Use when the user asks for release notes for a version.'
  });
  const install = path.join(home, '.claude', 'plugins', 'cache', 'acme', 'acme-tools', '1.0.0');
  writeSkill(path.join(install, 'skills', 'changelog-writer'), {
    name: 'changelog-writer',
    description: 'Keep CHANGELOG.md current. Use when the user asks to update the changelog.'
  });
  write(path.join(home, '.claude', 'plugins', 'installed_plugins.json'), json({
    version: 2,
    plugins: { 'acme-tools@acme': [{ scope: 'user', installPath: install, version: '1.0.0' }] }
  }));

  // OpenSpec archive: two changes about the same deploy work.
  const change = (folder, created, why, bullets) => {
    const dir = path.join(archive, folder);
    write(path.join(dir, '.openspec.yaml'), `schema: spec-driven\ncreated: ${created}\n`);
    write(path.join(dir, 'proposal.md'), `## Why\n\n${why}\n\n## What Changes\n\n${bullets.map((bullet) => `- ${bullet}`).join('\n')}\n`);
    write(path.join(dir, 'tasks.md'), '- [x] 1.1 Run `./scripts/deploy-sim.sh staging`\n- [x] 1.2 Run `pnpm test`\n');
    write(path.join(dir, 'specs', 'sim-runner', 'spec.md'), '## MODIFIED Requirements\n');
  };
  change('2026-09-04-deploy-sim-runner-healthcheck', '2026-09-03',
    'Each sim runner deploy to staging needs a manual health check. The steps live only in chat.',
    ['Add a health check to the sim runner deploy script.', 'Fail the deploy when the health check fails.', 'Post the check result to the team channel.']);
  change('2026-09-09-deploy-sim-runner-metrics', '2026-09-08',
    'After each sim runner deploy we open Grafana by hand to read the runner metrics.',
    ['Export the runner metrics after each deploy.', 'Link the Grafana panels in the deploy summary.']);

  // Previous run: one suggestion is now resolved, one is still open, one is stale.
  const proposal = (name, description, triggerPhrases) => ({ name, description, triggerPhrases, outline: [], change: null });
  const previous = path.join(project, '.skill-finder', 'runs', '20260901-090000-shop');
  write(path.join(previous, 'suggestions.json'), json({
    runId: '20260901-090000-shop',
    generatedAt: '2026-09-01T09:30:00.000Z',
    suggestions: [
      { id: 'sf-20260901-01', rank: 1, kind: 'new-skill', title: 'Write release notes from merged pull requests', candidateKeys: ['release notes'], catalogChecked: [], evidence: [], proposal: proposal('release-notes', 'Write release notes from merged pull requests.', ['write the release notes']), provenance: { episodeIds: [] } },
      { id: 'sf-20260901-02', rank: 2, kind: 'new-skill', title: 'Deploy the sim runner to staging', candidateKeys: ['deploy sim runner to staging'], catalogChecked: [], evidence: [], proposal: proposal('deploy-sim-runner', 'Deploy the sim runner to staging and check the dashboards.', ['deploy the sim runner']), provenance: { episodeIds: [] } },
      { id: 'sf-20260901-03', rank: 3, kind: 'new-skill', title: 'Rotate the grafana token', candidateKeys: ['rotate the grafana token'], catalogChecked: [], evidence: [], proposal: proposal('rotate-grafana-token', 'Rotate the grafana admin token and update the vault secret.', ['rotate the grafana token']), provenance: { episodeIds: [] } }
    ],
    rejected: []
  }));
  write(path.join(previous, 'report.md'), '# Skill suggestions: 20260901-090000-shop\n\nThree suggestions. See suggestions.json.\n');

  // Prepared run: the evidence pointer names line 2, an assistant tool call, so verify must block.
  const prepared = path.join(project, '.skill-finder', 'prepared', '20260922-100000-moved');
  const first = groups.deploy[0];
  write(path.join(prepared, 'run.json'), json({
    runId: '20260922-100000-moved',
    createdAt: '2026-09-22T10:00:00.000Z',
    cwd: project,
    sources: [`claude-sessions --store ${store}`],
    window: { since: null, until: null, maxEpisodes: null },
    thresholds: { minEpisodes: 3, minDays: 2 },
    summaryBackend: 'none',
    versions: { node: process.version, skillFinder: 1 }
  }));
  write(path.join(prepared, 'catalog.json'), json(buildCatalog({ cwd: project, home })));
  write(path.join(prepared, 'suggestions.json'), json({
    runId: '20260922-100000-moved',
    generatedAt: '2026-09-22T10:10:00.000Z',
    suggestions: [{
      id: 'sf-20260922-01',
      rank: 1,
      kind: 'new-skill',
      title: 'Deploy the sim runner to staging',
      kindReason: 'No catalog skill covers the deploy steps.',
      confidence: 'high',
      candidateKeys: ['deploy sim runner to staging'],
      recurrence: { episodes: 12, distinctDays: 12, sources: ['claude-sessions'] },
      cost: { median: 12, score: 144, corrections: 0 },
      catalogChecked: [],
      catalogMatch: null,
      evidence: [{ episodeId: `claude-sessions:${first.id}`, quote: first.prompt, pointer: { file: first.file, line: 2 } }],
      proposal: proposal('deploy-sim-runner', 'Deploy the sim runner to staging and verify the dashboards.', ['deploy the sim runner']),
      provenance: { runId: '20260922-100000-moved', sources: [], catalogSnapshot: null, episodeIds: [`claude-sessions:${first.id}`] }
    }],
    rejected: []
  }));
  write(path.join(prepared, 'report.md'), '# Skill suggestions: 20260922-100000-moved\n\n| Rank | Id | Kind | Title |\n| ---: | :--- | :--- | :--- |\n| 1 | sf-20260922-01 | new-skill | Deploy the sim runner to staging |\n');

  return { dest, project, home, store, archive, prepared };
}

if (isMain(import.meta.url)) {
  const world = buildWorld(path.resolve(process.argv[2] ?? '/tmp/skill-finder-world'));
  process.stdout.write(`${JSON.stringify(world)}\n`);
}
